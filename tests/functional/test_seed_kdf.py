"""
This module provides Ragger tests for the seeded key derivation, legacy and v2
"""

import json
import sys
from pathlib import Path

import pytest
from application_client.app_def import ClaType, DataObject, Errors, InsType, KeyGenMode, PassWord
from application_client.command_sender import CommandSender
from ragger.backend import BackendInterface
from ragger.error import ExceptionRAPDU
from seed_kdf import ecc_private, ecc_public, factor_legacy_rsa, rsa_modulus
from utils import KEY_TEMPLATES, check_pincode

# Public keys generated by the app 2.x in SEED mode, from the default Speculos seed
LEGACY_VECTORS = json.loads((Path(__file__).parent / "seed_legacy_vectors.json").read_text())

ROLES = {
    "sig": (DataObject.DO_SIG_ATTR, DataObject.DO_SIG_KEY),
    "dec": (DataObject.DO_DEC_ATTR, DataObject.DO_DEC_KEY),
    "aut": (DataObject.DO_AUT_ATTR, DataObject.DO_AUT_KEY),
}
ECC_TEMPLATES = ["nistp256", "secp256k1", "ed25519", "cv25519"]
LONG_TEMPLATES = ("rsa3072", "rsa4096")
FULL_ONLY = pytest.mark.skipif("--full" not in sys.argv, reason="skipping long test")


def _param(slot: int, template: str, role: str):
    marks = [FULL_ONLY] if template in LONG_TEMPLATES else []
    return pytest.param(slot, template, role, marks=marks, id=f"{slot}-{template}-{role}")


def _gen_key(client: CommandSender, slot: int, template: str, role: str, mode: KeyGenMode) -> bytes:
    """Generate a key on the given slot and return its public key template (7F49)"""

    attr_tag, key_tag = ROLES[role]
    check_pincode(client, PassWord.PW2)
    assert client.set_slot(slot).status == Errors.SW_OK
    check_pincode(client, PassWord.PW3)
    assert client.set_template(attr_tag, KEY_TEMPLATES[template]).status == Errors.SW_OK
    rapdu = client.generate_key(key_tag, mode)
    assert rapdu.status == Errors.SW_OK
    return rapdu.data


def _tlv(data: bytes, tag: int) -> bytes:
    """Value of a single byte tag in a 7F49 public key template"""

    offset = data.index(bytes([tag]), 3)
    length = data[offset + 1]
    offset += 2
    if length == 0x81:
        length = data[offset]
        offset += 1
    elif length == 0x82:
        length = int.from_bytes(data[offset : offset + 2], "big")
        offset += 2
    return data[offset : offset + length]


def _legacy_params() -> list:
    params = []
    for key in LEGACY_VECTORS:
        slot, template, role = key.split("/")
        params.append(_param(int(slot), template, role))
    return params


@pytest.mark.parametrize("slot, template, role", _legacy_params())
def test_seed_legacy(backend: BackendInterface, slot: int, template: str, role: str) -> None:
    client = CommandSender(backend)

    pubkey = _gen_key(client, slot, template, role, KeyGenMode.SEED_LEGACY)

    assert pubkey.hex() == LEGACY_VECTORS[f"{slot}/{template}/{role}"]


@pytest.mark.parametrize(
    "slot, template, role",
    [_param(0, t, r) for t in ECC_TEMPLATES for r in ROLES]
    + [_param(0, t, "sig") for t in ("rsa2048", "rsa3072", "rsa4096")]
    + [_param(1, "nistp256", "sig")],
)
def test_seed_v2(backend: BackendInterface, slot: int, template: str, role: str) -> None:
    client = CommandSender(backend)
    attributes = bytes.fromhex(KEY_TEMPLATES[template])

    pubkey = _gen_key(client, slot, template, role, KeyGenMode.SEED_V2)

    if template.startswith("rsa"):
        n = int.from_bytes(_tlv(pubkey, 0x81), "big")
        assert n == rsa_modulus(slot, role, attributes, True)
        assert n.bit_length() == int.from_bytes(attributes[1:3], "big")
        assert factor_legacy_rsa(n) is None
    else:
        d = ecc_private(slot, role, template, attributes, True)
        assert _tlv(pubkey, 0x86) == ecc_public(template, d)
    assert pubkey.hex() != LEGACY_VECTORS[f"{slot}/{template}/{role}"]


def test_seed_default_is_v2(backend: BackendInterface) -> None:
    client = CommandSender(backend)

    # SEED mode is ON by default
    default = _gen_key(client, 0, "ed25519", "sig", KeyGenMode.DEFAULT)
    v2 = _gen_key(client, 0, "ed25519", "sig", KeyGenMode.SEED_V2)

    assert default == v2


def test_seed_wrong_p2(backend: BackendInterface) -> None:
    client = CommandSender(backend)

    # Start from an empty card
    check_pincode(client, PassWord.PW3)
    client.send_terminate()
    client.send_activate()

    check_pincode(client, PassWord.PW3)
    with pytest.raises(ExceptionRAPDU) as err:
        backend.exchange(
            cla=ClaType.CLA_APP,
            ins=InsType.INS_GEN_ASYM_KEYPAIR,
            p1=0x80,
            p2=KeyGenMode.SEED_V2 + 1,
            data=bytes([DataObject.DO_SIG_KEY, 0x00]),
        )
    assert err.value.status == Errors.SW_WRONG_P1P2

    # No key was generated
    rapdu = client.read_key(DataObject.DO_SIG_KEY)
    assert rapdu.status == Errors.SW_REFERENCED_DATA_NOT_FOUND
